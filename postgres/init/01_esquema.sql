-- biblioteca-v2.sql
-- Esquema corregido a partir del DDL de dbdiagram.io (S8).
-- Ejecutar: docker compose exec postgres psql -U curso -d curso -f /scripts/biblioteca-v2.sql

DROP SCHEMA IF EXISTS biblioteca CASCADE;
CREATE SCHEMA biblioteca;
SET search_path TO biblioteca;

-- =====================================================================
-- USUARIOS: una sola tabla con columna rol (opcion 1 de la guia).
-- Justificacion: los 4 roles comparten todos sus datos y ninguno tiene
-- atributos propios, asi que no hay columnas opcionales (NULL) que justifiquen
-- tablas separadas. Reglas: 1 (entidad fuerte), 9 (dominios).
-- Limitacion: documento y correo son UNIQUE, asi que una misma persona no
-- puede tener dos roles (p. ej. bibliotecario que tambien presta libros).
-- =====================================================================
CREATE TABLE usuarios (
  id_usuario            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento             varchar(20)  NOT NULL UNIQUE,
  nombres               varchar(80)  NOT NULL,
  apellidos             varchar(80)  NOT NULL,
  correo                varchar(120) NOT NULL UNIQUE
                        CHECK (correo LIKE '%_@_%._%'),
  telefono              varchar(20),
  rol                varchar(15)  NOT NULL
                        CHECK (rol IN ('lector','bibliotecario','administrador','auditor')),
  usuario_activo        boolean      NOT NULL DEFAULT true,

  -- Relacion "Administra" (1:N autorreferencial, regla 6): la FK va en el lado N.
  -- Participacion parcial: puede ser NULL (un administrador no tiene administrador).
  id_administrador      integer,
  rol_administrador  varchar(15)
                        GENERATED ALWAYS AS (CASE WHEN id_administrador IS NULL
                                                  THEN NULL ELSE 'administrador' END) STORED,

  -- Permite que otras tablas apunten al usuario *con un rol concreto*.
  UNIQUE (id_usuario, rol),
  CONSTRAINT ck_no_se_administra_solo
    CHECK (id_administrador IS NULL OR id_administrador <> id_usuario),
  -- Solo un usuario con rol 'administrador' puede ser id_administrador.
  FOREIGN KEY (id_administrador, rol_administrador) REFERENCES usuarios (id_usuario, rol)
);

-- =====================================================================
-- CATALOGO
-- =====================================================================
CREATE TABLE categorias (
  id_categoria  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  genero        varchar(60) NOT NULL UNIQUE
);

CREATE TABLE autor (
  id_autor      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_autor  varchar(120) NOT NULL
);

-- ISBN pasa de integer a varchar: un ISBN de 13 digitos no cabe en integer.
-- Regla 6: relacion 1:N autor-libro (como en el diagrama de S8 y el CSV semilla):
-- la PK del lado "1" (autor) pasa como FK NOT NULL al lado N (libros).
CREATE TABLE libros (
  isbn              varchar(13) PRIMARY KEY
                    CHECK (isbn ~ '^[0-9]{10}([0-9]{3})?$'),
  id_categoria      integer NOT NULL REFERENCES categorias (id_categoria),
  id_autor          integer NOT NULL REFERENCES autor (id_autor),
  titulo            varchar(200) NOT NULL,
  editorial         varchar(100),
  anio_publicacion  integer CHECK (anio_publicacion BETWEEN 1000 AND 2100),
  libro_activo      boolean NOT NULL DEFAULT true
);

-- Regla 5: entidad debil. PK = PK de libros (isbn) + clave parcial (id_ejemplar,
-- numero de copia dentro de cada libro). ON DELETE CASCADE: sin libro no hay ejemplares.
CREATE TABLE ejemplares (
  isbn         varchar(13) NOT NULL REFERENCES libros (isbn) ON DELETE CASCADE,
  id_ejemplar  integer     NOT NULL,
  estado       varchar(20) NOT NULL DEFAULT 'disponible'
               CHECK (estado IN ('disponible','prestado','en_mantenimiento','perdido')),
  PRIMARY KEY (isbn, id_ejemplar)
);

-- =====================================================================
-- PRESTAMOS: N:M lector-ejemplar con atributos (regla 8); la fecha_hora entra en
-- la PK para permitir que el mismo lector pida el mismo ejemplar mas de una vez.
-- El bibliotecario es FK NOT NULL fuera de la PK.
-- Las columnas rol_* son constantes generadas: hacen que la FK compuesta solo
-- acepte usuarios con el rol correcto (lector / bibliotecario).
-- =====================================================================
CREATE TABLE prestamos (
  id_lector             integer      NOT NULL,
  rol_lector         varchar(15)  GENERATED ALWAYS AS ('lector') STORED,
  isbn                  varchar(13)  NOT NULL,
  id_ejemplar           integer      NOT NULL,
  fecha_hora_prestamo   timestamp    NOT NULL DEFAULT now(),
  id_bibliotecario      integer      NOT NULL,
  rol_bibliotecario  varchar(15)  GENERATED ALWAYS AS ('bibliotecario') STORED,
  fecha_vencimiento     date         NOT NULL,
  fecha_devolucion      date,
  PRIMARY KEY (id_lector, isbn, id_ejemplar, fecha_hora_prestamo),

  FOREIGN KEY (id_lector, rol_lector) REFERENCES usuarios (id_usuario, rol),
  FOREIGN KEY (id_bibliotecario, rol_bibliotecario) REFERENCES usuarios (id_usuario, rol),
  FOREIGN KEY (isbn, id_ejemplar) REFERENCES ejemplares (isbn, id_ejemplar),

  CONSTRAINT ck_vencimiento_posterior
    CHECK (fecha_vencimiento >= fecha_hora_prestamo::date),
  CONSTRAINT ck_devolucion_posterior
    CHECK (fecha_devolucion IS NULL OR fecha_devolucion >= fecha_hora_prestamo::date)
);

-- Un ejemplar (isbn + id_ejemplar) no puede tener dos prestamos abiertos a la vez.
CREATE UNIQUE INDEX uq_ejemplar_un_prestamo_abierto
  ON prestamos (isbn, id_ejemplar) WHERE fecha_devolucion IS NULL;
