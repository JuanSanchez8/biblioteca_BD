\set ON_ERROR_STOP on

DROP SCHEMA IF EXISTS programable CASCADE;
CREATE SCHEMA programable;
SET search_path TO programable;

CREATE TABLE libro (
    isbn         char(13)      PRIMARY KEY,
    titulo       varchar(200)  NOT NULL,
    autor        varchar(120)  NOT NULL,
    categoria    varchar(40)   NOT NULL,
    disponibles  integer       NOT NULL DEFAULT 0 CHECK (disponibles >= 0)  -- desnormalizado (S20)
);

CREATE TABLE ejemplar (
    id_ejemplar  integer   PRIMARY KEY,
    isbn         char(13)  NOT NULL REFERENCES libro
);

CREATE TABLE lector (
    documento  varchar(15)   PRIMARY KEY,
    nombres    varchar(80)   NOT NULL,
    apellidos  varchar(80)   NOT NULL,
    correo     varchar(120)  NOT NULL UNIQUE
);

-- Un lector puede tener varios teléfonos (atributo multivaluado, S11).
-- La FK todavía no dice qué hacer al borrar el lector: se cambia en la sección 3.
CREATE TABLE telefono_lector (
    documento  varchar(15)  REFERENCES lector,
    telefono   varchar(15)  CHECK (telefono ~ '^[0-9]{7,15}$'),
    PRIMARY KEY (documento, telefono)
);

CREATE TABLE prestamo (
    id                integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejemplar       integer      NOT NULL REFERENCES ejemplar,
    documento         varchar(15)  NOT NULL REFERENCES lector,
    fecha_prestamo    date         NOT NULL DEFAULT CURRENT_DATE,
    fecha_esperada    date         NOT NULL,
    fecha_devolucion  date,                       -- NULL = préstamo abierto
    CHECK (fecha_esperada > fecha_prestamo),
    CHECK (fecha_devolucion IS NULL OR fecha_devolucion >= fecha_prestamo)
);

