-- Conteos esperados con los datos del script S19: 4, 3, 5 y 8.
SELECT 'departamento' AS tabla, count(*) AS filas FROM departamento
UNION ALL SELECT 'zona', count(*) FROM zona
UNION ALL SELECT 'ciudad', count(*) FROM ciudad
UNION ALL SELECT 'envio', count(*) FROM envio;

-- Debe devolver cero filas: verifica la reconstruccion en ambos sentidos.
SELECT 'faltan en el esquema nuevo' AS diferencia, reconstruccion.*
FROM (
    SELECT e.num_guia, e.fecha, e.ciudad_destino, e.departamento,
           e.zona, e.tarifa_kg, e.peso_kg, e.valor::numeric
    FROM envio_original AS e
    EXCEPT
    SELECT n.num_guia, n.fecha, c.nombre, d.nombre,
           c.id_zona, n.tarifa_kg_aplicada, n.peso_kg,
           n.peso_kg * n.tarifa_kg_aplicada
    FROM envio AS n
    JOIN ciudad AS c ON c.id_ciudad = n.id_ciudad
    JOIN departamento AS d ON d.id_departamento = c.id_departamento
) AS reconstruccion
UNION ALL
SELECT 'sobran en el esquema nuevo', reconstruccion.*
FROM (
    SELECT n.num_guia, n.fecha, c.nombre, d.nombre,
           c.id_zona, n.tarifa_kg_aplicada, n.peso_kg,
           n.peso_kg * n.tarifa_kg_aplicada
    FROM envio AS n
    JOIN ciudad AS c ON c.id_ciudad = n.id_ciudad
    JOIN departamento AS d ON d.id_departamento = c.id_departamento
    EXCEPT
    SELECT e.num_guia, e.fecha, e.ciudad_destino, e.departamento,
           e.zona, e.tarifa_kg, e.peso_kg, e.valor::numeric
    FROM envio_original AS e
) AS reconstruccion;

DROP TABLE envio_original;

-- El valor se calcula con la tarifa aplicada al envío.
CREATE VIEW envio_con_valor AS
SELECT e.num_guia, e.fecha, c.nombre AS ciudad_destino,
       d.nombre AS departamento, c.id_zona AS zona,
       z.tarifa_kg_vigente, e.peso_kg, e.tarifa_kg_aplicada,
       e.peso_kg * e.tarifa_kg_aplicada AS valor
FROM envio AS e
JOIN ciudad AS c ON c.id_ciudad = e.id_ciudad
JOIN departamento AS d ON d.id_departamento = c.id_departamento
JOIN zona AS z ON z.id_zona = c.id_zona;

COMMIT;

-- (e) G07 debe mostrar valor = 24000.
SELECT num_guia, peso_kg, tarifa_kg_aplicada, valor
FROM envio_con_valor
WHERE num_guia = 'G07';

